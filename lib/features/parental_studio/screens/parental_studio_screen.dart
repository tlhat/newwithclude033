  @override
  void initState() {
    super.initState();
    // Pause child screen time tracking while parent is inside Parental Studio
    widget.appState.setParentalControlActive(true);
    // Immediately stop all story narration, voices, and background music upon entering Parental Studio
    CalmVoiceService.instance.stopAllAudioImmediatelyForParentalGate();
    final int mappedTabIndex = widget.initialTabIndex == 2
        ? 1
        : widget.initialTabIndex.clamp(0, 3);
    _tabController = TabController(
      length: 5,
      vsync: this,
      initialIndex: mappedTabIndex,
    );
    _remoteUrlCtrl =
        TextEditingController(text: widget.appState.remoteFeedUrl);
    _authApiCtrl = TextEditingController(text: widget.appState.authApiUrl);
    _emailWebhookCtrl =
        TextEditingController(text: widget.appState.emailWebhookUrl);
    _paymentApiCtrl =
        TextEditingController(text: widget.appState.paymentVerifyApiUrl);
    _merchantKeyCtrl =
        TextEditingController(text: widget.appState.merchantSecretKey);
    _pinUpdateCtrl = TextEditingController();
  }

  @override
  void dispose() {
    // Resume child screen time tracking when leaving Parental Studio
    widget.appState.setParentalControlActive(false);
    _tabController.dispose();
    _remoteUrlCtrl.dispose();
    _smartLinkImportCtrl.dispose();
    _vTitleCtrl.dispose();
    _vDescCtrl.dispose();
    _vUrlCtrl.dispose();
    _vPhraseCtrl.dispose();
    _vActivityCtrl.dispose();
    _vEmojiCtrl.dispose();
    _newChildNameCtrl.dispose();
    _parentSuggestionInputCtrl.dispose();
    _authApiCtrl.dispose();
    _emailWebhookCtrl.dispose();
    _paymentApiCtrl.dispose();
    _merchantKeyCtrl.dispose();
    _pinUpdateCtrl.dispose();
    super.dispose();
  }

