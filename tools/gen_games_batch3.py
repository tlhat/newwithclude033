def add(i,t,skill,lv,prompt,data,hints,explain=''):
    x={'id':'b3_'+i,'type':t,'prompt':prompt,'hints':hints,'correct':'برافو يا بطل!','wrong':'قريب، جرّب تاني.','data':data,'skill':skill,'level':lv}
    if explain: x['explain']=explain
