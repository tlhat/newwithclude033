def ch(skill,rows,hints):
    rr=random.Random(sum(map(ord,skill)));n=len(rows)
    for i,(p,o,c,ex) in enumerate(rows):
        right=o[c];o=o[:];rr.shuffle(o);c=o.index(right)
        add(f'{skill}{i}','choice',skill,1+min(2,i*3//n),p,{'options':o,'correct':c},hints,ex)
def order(skill,rows,hints):
    rr=random.Random(sum(map(ord,skill)))
    for i,(p,steps) in enumerate(rows):
        sh=steps[:]
        while sh==steps: rr.shuffle(sh)
        add(f'{skill}{i}','ordering',skill,1+min(2,i*3//len(rows)),p,{'items':sh,'order':steps},hints)
